/** اگر ردیفی برای قواعد دانش‌نامه نیست، بساز (idempotent — متن به‌روز هم جایگزین می‌شود). */
export async function seedTraderKnowledge(): Promise<number> {
  let n = 0
  for (const r of TRADER_CURRICULUM) {
    await db.brainLesson.upsert({
      where: { key: r.key },
      update: { titleFa: r.titleFa, bodyFa: r.bodyFa, statsFa: `اعمال در: ${r.appliedFa}` },
      create: {
        key: r.key,
        kind: 'curriculum',
        titleFa: r.titleFa,
        bodyFa: r.bodyFa,
        statsFa: `اعمال در: ${r.appliedFa}`,
        confidence: 100,
        delta: 0,
        active: true,
      },
    })
    n++
  }
  return n
}

export function curriculumCountFa(): string {
  return faNum(TRADER_CURRICULUM.length, 0)
}
